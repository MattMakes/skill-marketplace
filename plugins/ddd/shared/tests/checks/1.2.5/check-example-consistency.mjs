#!/usr/bin/env node
// Gate G2 for leaf 1.2.5: the example's manifest, markdown and diagrams are
// consistent with its step JSON.
//
//   node plugins/ddd/shared/tests/checks/1.2.5/check-example-consistency.mjs <example-root>
//
// <example-root> is the folder holding `ddd/` (plugins/ddd/shared/examples/mealkit).
// On a temp copy, with cwd = the copy's root and the workspace addressed as
// `ddd` (as golden.mjs does), it:
//   - runs every markdown renderer (discover render, strategize render,
//     connect render --write-md, define render, contracts render, organise
//     mermaid) and requires exit 0
//   - diffs every regenerated .md against the committed one, ignoring only
//     the generated-timestamp line
//   - renders every diagram fresh with renderAll and requires each SVG to
//     equal the committed diagrams/<id>.svg byte for byte
//   - regenerates each step's decision pictures and requires them to equal
//     the committed diagrams/decisions/*.svg
//   - requires every manifest step entry that records an open_questions
//     count to match the step JSON
// Prints "example-consistency verification passed"; exit 0 pass, 1 failure,
// 2 misuse.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SHARED = path.resolve(HERE, "../../..");
const CLI = path.join(SHARED, "bin", "ddd.mjs");

const args = process.argv.slice(2);
if (args.length !== 1 || args[0].startsWith("-")) {
  console.error("usage: node check-example-consistency.mjs <example-root>");
  process.exit(2);
}
const root = path.resolve(args[0]);
const committed = path.join(root, "ddd");
if (!fs.existsSync(path.join(committed, "manifest.json"))) {
  console.error(`usage: ${args[0]} has no ddd/manifest.json`);
  process.exit(2);
}

const { loadWorkspace } = await import(path.join(SHARED, "lib", "workspace.mjs"));
const { renderAll } = await import(path.join(SHARED, "lib", "render", "diagrams", "index.mjs"));
const decision = await import(path.join(SHARED, "lib", "render", "diagrams", "decision.mjs"));

const failures = [];
const fail = (msg) => failures.push(msg);

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ddd-example-consistency-"));
const copyRoot = path.join(tmp, "copy");
fs.cpSync(root, copyRoot, { recursive: true });
const copy = path.join(copyRoot, "ddd");

const ENV = { ...process.env, DDD_NO_RENDER: "1", TZ: "UTC", NO_COLOR: "1" };
const RENDERERS = [
  ["discover", "render", "ddd/02-discover/discover.json"],
  ["strategize", "render", "ddd"],
  ["connect", "render", "ddd", "--write-md"],
  ["define", "render", "ddd"],
  ["contracts", "render", "ddd"],
  ["organise", "mermaid", "ddd"],
];
for (const argv of RENDERERS) {
  const res = spawnSync(process.execPath, [CLI, ...argv], { cwd: copyRoot, encoding: "utf8", env: ENV });
  if (res.status !== 0) fail(`ddd ${argv.join(" ")} exited ${res.status}: ${(res.stderr || res.stdout).trim().split("\n").slice(-3).join(" / ")}`);
}

// ---- Markdown ------------------------------------------------------------------------------------

function walk(dir, pred, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, pred, out);
    else if (pred(p)) out.push(p);
  }
  return out;
}
const rel = (base, p) => path.relative(base, p).split(path.sep).join("/");

// Only the generated-timestamp line may differ between a render and the
// committed file: `<!-- generated by ... on <timestamp>. ... -->`.
const GENERATED_TS = /(<!-- generated by .*? on )\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ/g;
const normaliseMd = (s) => s.replace(GENERATED_TS, "$1<TS>");

const committedMd = new Set(walk(committed, (p) => p.endsWith(".md")).map((p) => rel(committed, p)));
const copyMd = new Set(walk(copy, (p) => p.endsWith(".md")).map((p) => rel(copy, p)));
for (const r of committedMd) if (!copyMd.has(r)) fail(`renderers removed ${r}, which is committed`);
for (const r of copyMd) {
  if (!committedMd.has(r)) { fail(`renderers wrote ${r}, which is not committed`); continue; }
  const a = normaliseMd(fs.readFileSync(path.join(committed, r), "utf8"));
  const b = normaliseMd(fs.readFileSync(path.join(copy, r), "utf8"));
  if (a !== b) {
    const la = a.split("\n"); const lb = b.split("\n");
    let i = 0; while (i < la.length && i < lb.length && la[i] === lb[i]) i += 1;
    fail(`${r} differs from its render at line ${i + 1}: committed ${JSON.stringify(la[i] ?? "<eof>")} vs rendered ${JSON.stringify(lb[i] ?? "<eof>")}`);
  }
}

// ---- Diagrams --------------------------------------------------------------------------------------

const ws = loadWorkspace(copy);
const freshDir = path.join(tmp, "diagrams");
const r = await renderAll(ws, { outDir: freshDir });
for (const s of r.skipped) fail(`renderAll skipped ${s.id}: ${s.reason}`);
for (const w of r.warnings) fail(`renderAll warning: ${w}`);
if (!r.written.length) fail("renderAll wrote nothing");
for (const w of r.written) {
  for (const [label, fresh] of [["svg", w.svg], ["layout", w.layout]]) {
    const target = path.join(committed, "diagrams", path.basename(fresh));
    if (!fs.existsSync(target)) { fail(`diagrams/${path.basename(fresh)} is not committed`); continue; }
    if (!fs.readFileSync(fresh).equals(fs.readFileSync(target))) fail(`diagrams/${path.basename(fresh)} (${label}) differs from a fresh render`);
  }
}
const committedSvgs = fs.existsSync(path.join(committed, "diagrams"))
  ? fs.readdirSync(path.join(committed, "diagrams")).filter((f) => f.endsWith(".svg")) : [];
for (const f of committedSvgs) if (!r.written.some((w) => path.basename(w.svg) === f)) fail(`diagrams/${f} is committed but renderAll does not produce it`);

// Decision pictures: the CLI writes diagrams/decisions/<Did>.svg for the first
// step holding <Did>; a later step's decision with the same id is committed
// as <step>-<Did>.svg. Both must equal a fresh decisionSvg.
const decDir = path.join(committed, "diagrams", "decisions");
const expectedDec = new Set();
for (const step of Object.keys(ws.steps || {})) {
  for (const d of ws.steps[step]?.decisions || []) {
    const first = decision.findDecision(ws, d.id);
    const name = first && first.step === step ? `${d.id}.svg` : `${step}-${d.id}.svg`;
    expectedDec.add(name);
    const target = path.join(decDir, name);
    if (!fs.existsSync(target)) { fail(`diagrams/decisions/${name} is not committed for ${step} ${d.id}`); continue; }
    const fresh = await decision.decisionSvg(ws, step, d, { standalone: true });
    for (const w of fresh.warnings) fail(`${step} ${d.id}: ${w}`);
    if (fresh.svg !== fs.readFileSync(target, "utf8")) fail(`diagrams/decisions/${name} differs from a fresh render of ${step} ${d.id}`);
  }
}
if (fs.existsSync(decDir)) {
  for (const f of fs.readdirSync(decDir).filter((x) => x.endsWith(".svg"))) if (!expectedDec.has(f)) fail(`diagrams/decisions/${f} is committed but no decision produces it`);
}

// ---- Manifest ---------------------------------------------------------------------------------------

const manifest = JSON.parse(fs.readFileSync(path.join(committed, "manifest.json"), "utf8"));
for (const [step, entry] of Object.entries(manifest.steps || {})) {
  const doc = ws.steps?.[step];
  if (entry.status === "done" && !doc) fail(`manifest marks ${step} done but its JSON is not loaded`);
  if (typeof entry.open_questions === "number" && doc) {
    const n = Array.isArray(doc.open_questions) ? doc.open_questions.length : 0;
    if (n !== entry.open_questions) fail(`manifest says ${step} has ${entry.open_questions} open question(s), ${step}.json has ${n}`);
  }
}

fs.rmSync(tmp, { recursive: true, force: true });

if (failures.length) {
  for (const f of failures) console.error(`FAIL ${f}`);
  console.error(`example-consistency verification FAILED: ${failures.length} problem(s)`);
  process.exit(1);
}
console.log(`markdown files compared: ${copyMd.size}; diagrams compared: ${r.written.length}; decision pictures: ${expectedDec.size}`);
console.log("example-consistency verification passed");
