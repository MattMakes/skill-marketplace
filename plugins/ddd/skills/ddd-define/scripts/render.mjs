function renderSystem(ws, define, facts, system, parties) {
  const L = [];
  const P = (s) => L.push(s);
  P(`# System context — ${pystr(system.title)}`);
  P("");
  L.push(...plainWordsBlock(define));
  P(`<!-- ${MARK} from ${ws.rel}/07-define/define.json on ${now()}. Edit define.json and re-render; delete this line to protect hand edits. -->`);
  P("");
  const one = pystrip(or(get(system, "one_liner"), ""));
  P((one ? pyrstrip(one, ".") + ". " : "") +
    "C4 level 1: the system as a single box, the people who use it and the external systems it depends on. " +
    "No technology or internal structure here — that lives in the bounded context canvases and in `ddd-code`.");
  P("");
  P("```mermaid");
  P(pyrstrip(pystr(get(define, "system_context_c4_mermaid", ""))));
  P("```");
  P("");
  P("## People and external systems");
  P("");
  P("| Party | Type | Sends to the system | Receives from the system |");
  P("|---|---|---|---|");
  const partiesTbl = new Map();
  for (const c of get(define, "canvases", [])) {
    const f = facts.get(c.context);
    if (!truthy(f)) continue;
    for (const [side, key, arrow] of [["inbound", "in", "→"], ["outbound", "out", "←"]]) {
      for (const coll of get(c, side, [])) {
        const k = pkind(f, parties, coll.collaborator);
        if (k === "person" || k === "external system") {
          if (!partiesTbl.has(coll.collaborator)) partiesTbl.set(coll.collaborator, { name: pname(f, parties, coll.collaborator), type: k, in: [], out: [] });
          const p = partiesTbl.get(coll.collaborator);
          for (const m of get(coll, "messages", [])) {
            const s = `${pystr(get(m, "name", m.id))} ${arrow} \`${c.context}\``;
            if (!p[key].includes(s)) p[key].push(s);
          }
        }
      }
    }
  }
  for (const [pid, p] of partiesTbl) P(`| ${cell(p.name)} (\`${pystr(pid)}\`) | ${p.type} | ${cell(or(p.in.join("; "), "—"))} | ${cell(or(p.out.join("; "), "—"))} |`);
  if (!partiesTbl.size) P("| — | | | |");
  P("");
  P("## Bounded contexts and deployables");
  P("");
  P(`_Topology_: ${or(get(system, "topology_style"), "—")}, ${system.deployables.length} deployable(s), ${system.teams.length} team(s).`);
  P("");
  P("| Context | Purpose | Domain | Roles | Team | Deployable | Canvas |");
  P("|---|---|---|---|---|---|---|");
  for (const c of get(define, "canvases", [])) {
    const f = facts.get(c.context);
    if (!truthy(f)) continue;
    const team = or(f.team, {}), dep = or(f.deployable, {});
    const link = pystr(c.canvas_path).split("/07-define/").pop();
    P(`| **${cell(or(get(c, "name"), f.name))}** (\`${c.context}\`) | ${cell(firstSentence(get(c, "purpose")))} | ${pystr(get(get(c, "strategic_classification", {}), "domain", "—"))} | ${cell(get(c, "domain_roles", []).join(", "))} | ${cell(get(team, "name"))} | ${cell(get(dep, "name"))} (${pystr(get(dep, "kind", "—"))}) | [${link}](${link}) |`);
  }
  P("");
  P("### Context relationships (from decompose)");
  P("");
  P("| Id | Upstream | Downstream | Pattern | Why |");
  P("|---|---|---|---|---|");
  for (const r of system.relationships) {
    P(`| ${pystr(get(r, "id"))} | \`${pystr(get(r, "upstream"))}\` | \`${pystr(get(r, "downstream"))}\` | ${pystr(get(r, "pattern"))} | ${cell(get(r, "description"))} |`);
  }
  if (!system.relationships.length) P("| — | | | | |");
  P("");
  P("## Quality attributes (Quality Storming, light)");
  P("");
  const qas = get(define, "quality_attributes", []);
  if (truthy(qas)) {
    P("| Context | Attribute | Priority | Requirement | Scenario |");
    P("|---|---|---|---|---|");
    const ordered = [...facts.keys()].sort((a, b) => {
      const ka = facts.get(a).classification.domain !== "core" ? 1 : 0;
      const kb = facts.get(b).classification.domain !== "core" ? 1 : 0;
      return ka - kb || (a < b ? -1 : a > b ? 1 : 0);
    });
    const order = new Map(ordered.map((X, i) => [X, i]));
    const key = (q) => [order.get(get(q, "context")) ?? 99, PRIORITY_RANK[get(q, "priority")] ?? 3];
    for (const q of [...qas].sort((a, b) => { const [x1, y1] = key(a), [x2, y2] = key(b); return x1 - x2 || y1 - y2; })) {
      P(`| \`${pystr(get(q, "context"))}\` | ${cell(get(q, "attribute"))} | ${pystr(get(q, "priority"))} | ${cell(get(q, "requirement"))} | ${cell(get(q, "scenario"))} |`);
    }
  } else {
    P("_None recorded._");
  }
  P("");
  P("_Constraints these trace to (understand)_: " + or(system.constraints.map((c) => `${pystr(get(c, "id"))} [${pystr(get(c, "kind"))}] ${pystr(get(c, "text"))}`).join("; "), "—"));
  P("");
  P("## Open questions and assumptions (this step)");
  P("");
  for (const a of get(define, "assumptions", [])) P(`- Assumption ${pystr(get(a, "id"))} (${pystr(get(a, "confidence"))}): ${pystr(get(a, "text"))}`);
  for (const q of get(define, "open_questions", [])) P(`- Question ${pystr(get(q, "id"))}${truthy(get(q, "blocking")) ? " — BLOCKING" : ""} (owner: ${pystr(get(q, "owner", "—"))}): ${pystr(get(q, "text"))}`);
  for (const nt of get(define, "notes_for_downstream", [])) P(`- Note ${pystr(get(nt, "id"))} for ${get(nt, "for", []).join(", ")} (${pystr(get(nt, "kind", "other"))}): ${pystr(get(nt, "text"))}`);
  if (!truthy(get(define, "assumptions")) && !truthy(get(define, "open_questions")) && !truthy(get(define, "notes_for_downstream"))) P("_None._");
  P("");
  P("---");
  P("_Notation: C4 model level 1 (c4model.com); rendered with Mermaid `C4Context`. Persons are people, `System_Ext` are systems outside our control._");
  return L.join("\n") + "\n";
}

// ---------------------------------------------------------------- glossary
function norm(s) {
  return pystrip(or(s, "")).toLowerCase().replace(/\s+/g, " ").replace(/[\s.]+$/, "");
}

function renderGlossary(ws, define, facts, system) {
  const text = or(ws.glossary_md, `# Ubiquitous language: ${pystr(system.title)}\n\n## Shared\n`);
  const head = [], sections = new Map();
  let cur = null;
  for (const line of splitlines(text)) {
    if (hasMark(line)) continue; // an earlier render's marker is never carried over: exactly one is written below
    if (line.startsWith("## ")) {
      cur = pystrip(line.slice(3));
      sections.set(cur, []);
      continue;
    }
    (truthy(cur) ? sections.get(cur) : head).push(line);
  }
  const sharedDefs = new Map();
  for (const e of parseGlossary(text).get("Shared") || []) sharedDefs.set(e.term, e.definition);
  const ctxHeadings = new Set();
  for (const c of get(define, "canvases", [])) {
    const f = facts.get(c.context);
    const nm = or(get(c, "name"), truthy(f) ? f.name : c.context);
    ctxHeadings.add(`${pystr(nm)} context`.toLowerCase());
    ctxHeadings.add(`${c.context} context`.toLowerCase());
  }
  const kept = new Map([...sections].filter(([h]) => !ctxHeadings.has(h.toLowerCase()) && !h.toLowerCase().endsWith(" context (deprecated)")));
  // a Shared term that two or more contexts define differently is a boundary: flag it on the Shared line, keep the definition
  const ctxDefs = new Map();
  for (const c of get(define, "canvases", [])) {
    for (const t of get(c, "ubiquitous_language", [])) {
      if (!ctxDefs.has(get(t, "term"))) ctxDefs.set(get(t, "term"), new Set());
      ctxDefs.get(get(t, "term")).add(norm(get(t, "definition")));
    }
  }
  // Written with a plain hyphen (some repos ban em dashes), but recognised in any dash form so a
  // re-run over a glossary an earlier version wrote does not append a second marker to the line.
  const SPLIT = "_(meaning differs by context - see below)_";
  const SPLIT_RE = /_\(meaning differs by context\s*[-\u2013\u2014]\s*see below\)_/;
  const out = [...head];
  while (out.length && !pystrip(out[out.length - 1])) out.pop();
  out.push("");
  for (const [h, body0] of kept) {
    out.push(`## ${h}`);
    const body = [...body0];
    while (body.length && !pystrip(body[body.length - 1])) body.pop();
    if (h === "Shared") {
      for (let i = 0; i < body.length; i++) {
        const line = body[i];
        const m = line.match(/^\*\*(.+?)\*\*/);
        if (m && !SPLIT_RE.test(line)) {
          const term = pystrip(m[1]);
          const all = ctxDefs.get(term) ?? new Set();
          const defs = new Set([...all].filter((d) => d !== norm(sharedDefs.get(term) ?? null)));
          if (defs.size >= 1 && all.size >= 2) body[i] = pyrstrip(line) + " " + SPLIT;
        }
      }
    }
    out.push(...body);
    out.push("");
  }
  out.push(`<!-- per-context sections below are ${MARK} from ${ws.rel}/07-define/define.json; edit define.json (canvases[].ubiquitous_language) and re-render -->`);
  out.push("");
  for (const c of get(define, "canvases", [])) {
    const f = facts.get(c.context);
    const nm = or(get(c, "name"), truthy(f) ? f.name : c.context);
    out.push(`## ${pystr(nm)} context`);
    const specific = [], sameAsShared = [];
    for (const t of get(c, "ubiquitous_language", [])) {
      const sd = sharedDefs.has(get(t, "term")) ? sharedDefs.get(get(t, "term")) : null;
      (sd !== null && norm(sd) === norm(get(t, "definition")) ? sameAsShared : specific).push(t);
    }
    for (const t of specific) {
      let line = `**${pystr(get(t, "term"))}** — ${pyrstrip(pystr(get(t, "definition", "")), ".")}.`;
      if (truthy(get(t, "avoid"))) line += ` _Avoid_: ${t.avoid.join(", ")}`;
      if (sharedDefs.has(get(t, "term"))) line += " _(differs from the shared meaning — a boundary)_";
      out.push(line);
    }
    if (sameAsShared.length) out.push(`_Uses the shared meaning of_: ${sameAsShared.map((t) => "**" + pystr(t.term) + "**").join(", ")}`);
    if (!specific.length && !sameAsShared.length) out.push("_No context-specific terms recorded yet._");
    out.push("");
  }
  return pyrstrip(out.join("\n"), "\n") + "\n";
}

// ---------------------------------------------------------------- main
// The generated-line guard (invariant 4): a file that exists, is not blank and no longer
// carries MARK was edited by hand, so it is skipped unless --force.
function write(file, content, force, skipped) {
  if (fs.existsSync(file) && !force) {
    const old = fs.readFileSync(file, "utf8").replace(/\r\n?/g, "\n");
    if (!hasMark(old) && pystrip(old)) { skipped.push(file); return false; }
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

const SPEC = {
  "--context": { dest: "context", nargs: "*" },
  "--check-only": { dest: "check_only", action: "store_true" },
  "--force": { dest: "force", action: "store_true" },
  "--no-glossary": { dest: "no_glossary", action: "store_true" },
};
const USAGE = "usage: ddd define render [ddd_dir] [--context [ID ...]] [--check-only] [--force] [--no-glossary]";

export function main(argv) {
  const out = (s) => process.stdout.write(s);
  let a;
  try {
    a = parseArgs(SPEC, argv);
  } catch (e) {
    if (e instanceof UsageError) { process.stderr.write(`${USAGE}\nddd define render: error: ${e.message}\n`); return 2; }
    throw e;
  }
  if (a.help) { out(USAGE + "\n"); return 0; }
  try {
    return run(a, out);
  } catch (e) {
    if (e instanceof ExitError) { process.stderr.write(e.message + "\n"); return e.exitCode; }
    throw e;
  }
}

function run(a, out) {
  const ws = loadWorkspace(a.ddd_dir);
  const define = ws.steps.define;
  if (!truthy(define)) throw new ExitError(`error: ${path.join(ws.ddd_dir, "07-define/define.json")} not found — run ddd define prefill --write first`);
  const [facts, system] = buildFacts(ws);
  const parties = partyIndex(ws);
  const only = truthy(a.context) ? new Set(a.context) : null;
  const [errors, warnings] = lint(ws, define, facts, parties, only);
  for (const w of warnings) out(`warning: ${w}\n`);
  if (errors.length) {
    out(`\n${errors.length} lint error(s) — nothing rendered:\n`);
    for (const e of errors) out(`  - ${e}\n`);
    return 1;
  }
  out("lint: OK\n");
  if (a.check_only) return 0;
  const written = [], skipped = [];
  for (const c of define.canvases) {
    if (only && !only.has(c.context)) continue;
    const file = pyjoin(ws.project_root, c.canvas_path);
    if (write(file, renderCanvas(ws, define, facts, parties, c), a.force, skipped)) written.push(file);
  }
  const sysPath = path.join(ws.ddd_dir, "07-define", "system-context.md");
  if (write(sysPath, renderSystem(ws, define, facts, system, parties), a.force, skipped)) written.push(sysPath);
  if (!a.no_glossary) {
    const gpath = path.join(ws.ddd_dir, "glossary.md");
    const content = renderGlossary(ws, define, facts, system);
    fs.mkdirSync(ws.ddd_dir, { recursive: true });
    fs.writeFileSync(gpath, content);
    written.push(gpath);
  }
  for (const p of written) out(`wrote ${p}\n`);
  for (const p of skipped) out(`skipped (hand-edited, no marker; use --force to overwrite): ${p}\n`);
  const pre = path.join(ws.ddd_dir, "07-define", ".prefill");
  if (!only && fs.existsSync(pre) && fs.statSync(pre).isDirectory()) {
    fs.rmSync(pre, { recursive: true, force: true });
    out(`removed ${pre} (pre-fill briefs are scaffolding; re-run ddd define prefill to regenerate them)\n`);
  }
  return 0;
}
