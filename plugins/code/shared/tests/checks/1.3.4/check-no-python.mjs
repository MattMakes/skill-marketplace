#!/usr/bin/env node
// G4 for leaf 1.3.4: the Node ports of the define step neither import nor spawn Python.
//
// Scans skills/ddd-define/scripts/*.mjs with comments and string literals blanked out
// (the ports legitimately print Python-era hints such as `run prefill.py --write first`
// and carry the `render.py` marker text until leaf 1.4.1 rewords them, and their comments
// explain the Python semantics they preserve) and fails on:
//   - any import/require of node:child_process, or a spawn/exec call;
//   - any import/require whose specifier ends in .py;
//   - the identifier python / python3 anywhere in code.
// A positive control (a temp file that spawns python3 and one that imports a .py path)
// proves the scanner detects what it claims to, following the 1.1.4 pattern.
//
// Usage: node plugins/code/shared/tests/checks/1.3.4/check-no-python.mjs --leaf 1.3.4
// Exit 0 pass, 1 fail, 2 usage.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLUGIN = path.resolve(HERE, "..", "..", "..", "..");
const SCRIPTS = path.join(PLUGIN, "skills", "ddd-define", "scripts");
const MARKER = "no-python verification passed";
const EXPECTED = ["prefill.mjs", "render.mjs"];

if (process.argv.length !== 4 || process.argv[2] !== "--leaf" || process.argv[3] !== "1.3.4") {
  console.error("usage: node plugins/code/shared/tests/checks/1.3.4/check-no-python.mjs --leaf 1.3.4");
  process.exit(2);
}

// Blank out comments and string literals, keeping line structure so findings have line
// numbers. Template literals are treated as plain strings; a regex literal is not
// recognised, which errs on the side of reporting more, never less.
export function codeOnly(src) {
  let out = "";
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === "/" && d === "/") {
      while (i < n && src[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && d === "*") {
      i += 2;
      while (i < n && !(src[i] === "*" && src[i + 1] === "/")) { out += src[i] === "\n" ? "\n" : ""; i++; }
      i += 2;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      const q = c;
      out += q;
      i++;
      while (i < n && src[i] !== q) {
        if (src[i] === "\\") { i += 2; continue; }
        if (src[i] === "\n") out += "\n";
        i++;
      }
      out += q;
      i++;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

const RULES = [
  { name: "process spawn/exec call", re: /\b(?:spawn|spawnSync|exec|execSync|execFile|execFileSync|fork)\s*\(/ },
  { name: "python identifier", re: /\bpython3?\b/i },
];
// Import specifiers live in strings, so these two rules look at the raw source, not the
// blanked one: an import/require of child_process, and one whose specifier ends in `.py`.
const CHILD_IMPORT = /\b(?:import\b[^\n;]*\bfrom\s*|import\s*\(\s*|require\s*\(\s*)['"`](?:node:)?child_process['"`]/;
const PY_IMPORT = /\b(?:import\s*(?:[^'"`\n;]*from\s*)?|require\s*\(\s*)['"`][^'"`\n]*\.py(?:[?#][^'"`\n]*)?['"`]/;

export function findings(file) {
  const src = fs.readFileSync(file, "utf8");
  const code = codeOnly(src);
  const hits = [];
  code.split("\n").forEach((line, idx) => {
    for (const r of RULES) if (r.re.test(line)) hits.push({ rule: r.name, line: idx + 1, text: line.trim().slice(0, 120) });
  });
  src.split("\n").forEach((line, idx) => {
    if (CHILD_IMPORT.test(line)) hits.push({ rule: "child_process import", line: idx + 1, text: line.trim().slice(0, 120) });
    if (PY_IMPORT.test(line)) hits.push({ rule: ".py import", line: idx + 1, text: line.trim().slice(0, 120) });
  });
  return hits;
}

const failures = [];

// 1. Positive control: a scanner that cannot see the problem is not a gate.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ddd-no-python-1.3.4-"));
try {
  const bad1 = path.join(tmp, "spawns.mjs");
  fs.writeFileSync(bad1, '// harmless comment about python3\nimport { spawnSync } from "node:child_process";\nexport const r = spawnSync("python3", ["x.py"]);\n');
  const bad2 = path.join(tmp, "imports.mjs");
  fs.writeFileSync(bad2, 'import helper from "../scripts/prefill.py";\nconst other = require("./render.py");\nexport { helper, other };\n');
  const bad3 = path.join(tmp, "ident.mjs");
  fs.writeFileSync(bad3, 'const python = "just a name";\nexport default python;\n');
  const good = path.join(tmp, "clean.mjs");
  fs.writeFileSync(good, '// this comment mentions python3 and spawn(\nexport const hint = "run prefill.py --write first; render.py removes .prefill/";\nexport const mark = `generated by ddd-define/scripts/render.py`;\n');
  const h1 = findings(bad1), h2 = findings(bad2), h3 = findings(bad3), h0 = findings(good);
  if (!h1.some((h) => h.rule === "child_process import") || !h1.some((h) => h.rule === "process spawn/exec call")) {
    failures.push(`control: a file that spawns python3 must be flagged for the import and the call, got ${JSON.stringify(h1)}`);
  }
  if (h2.filter((h) => h.rule === ".py import").length !== 2) failures.push(`control: two .py imports must be flagged, got ${JSON.stringify(h2)}`);
  if (!h3.some((h) => h.rule === "python identifier")) failures.push(`control: a python identifier must be flagged, got ${JSON.stringify(h3)}`);
  if (h0.length) failures.push(`control: Python-era hints inside strings and comments must not be flagged, got ${JSON.stringify(h0)}`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

// 2. The leaf's files exist and are clean.
const files = fs.existsSync(SCRIPTS) ? fs.readdirSync(SCRIPTS).filter((f) => f.endsWith(".mjs")).sort() : [];
for (const f of EXPECTED) if (!files.includes(f)) failures.push(`missing ${path.join(SCRIPTS, f)}`);
let scanned = 0;
for (const f of files) {
  const file = path.join(SCRIPTS, f);
  scanned++;
  for (const h of findings(file)) failures.push(`${path.relative(PLUGIN, file)}:${h.line}: ${h.rule}: ${h.text}`);
}

if (failures.length) {
  console.error("no-python verification FAILED:");
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log(`scanned ${scanned} file(s) under ${path.relative(PLUGIN, SCRIPTS)}: no Python import, spawn or identifier (controls detected 3 bad files, ignored 1 clean file)`);
console.log(MARKER);
