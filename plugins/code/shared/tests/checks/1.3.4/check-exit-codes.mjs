#!/usr/bin/env node
// G3 for leaf 1.3.4: the exit-code contract of `ddd define prefill` and `ddd define render`.
//
// Success is 0, a render lint failure is 1, a usage error is 2. Everything runs on fresh
// temporary copies of the golden fixtures (fixtures/build.mjs), never on the shipped
// example, and only the Node CLI is spawned, so the check keeps working after leaf 1.4.1
// deletes the Python scripts.
//
// One pinned surprise is asserted rather than "fixed": the Python twin used
// sys.exit("error: ...") for a missing workspace or a missing define.json, which is exit 1
// with the message on stderr, and the goldens record exactly that (truncated-3
// define-render). The design table says usage/IO is 2; parity with the recorded goldens
// wins in phase 1.3, and this check documents the actual value so the discrepancy cannot
// drift silently.
//
// The same runs also cover the three define invariants from the design (§6): render never
// writes define.json (3), the generated-line guard skips a hand-edited file unless --force
// (4), and .prefill/ is removed only after a full successful render, not on --check-only,
// --context or a lint failure (7).
//
// Usage: node plugins/code/shared/tests/checks/1.3.4/check-exit-codes.mjs 1.3.4
// Exit 0 pass, 1 fail, 2 usage.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { materialise } from "../../fixtures/build.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLUGIN = path.resolve(HERE, "..", "..", "..", "..");
const DDD = path.join(PLUGIN, "shared", "bin", "ddd.mjs");
const MARKER = "exit-codes verification passed";
const MARK = "generated by ddd define render";

if (process.argv.length !== 3 || process.argv[2] !== "1.3.4") {
  console.error("usage: node plugins/code/shared/tests/checks/1.3.4/check-exit-codes.mjs 1.3.4");
  process.exit(2);
}

const failures = [];
const assert = (cond, msg) => { if (!cond) failures.push(msg); };

function run(root, ...args) {
  const r = spawnSync(process.execPath, [DDD, ...args], {
    cwd: root,
    env: { ...process.env, DDD_NO_RENDER: "1", TZ: "UTC", NO_COLOR: "1" },
    encoding: "utf8",
  });
  return { code: r.status, out: r.stdout, err: r.stderr };
}

function expect(label, res, code, { out, err } = {}) {
  assert(res.code === code, `${label}: expected exit ${code}, got ${res.code}\n    stdout: ${res.out.trim().slice(0, 300)}\n    stderr: ${res.err.trim().slice(0, 300)}`);
  if (out !== undefined) assert(res.out.includes(out), `${label}: stdout should contain ${JSON.stringify(out)}`);
  if (err !== undefined) assert(res.err.includes(err), `${label}: stderr should contain ${JSON.stringify(err)}`);
}

const editJson = (file, fn) => {
  const j = JSON.parse(fs.readFileSync(file, "utf8"));
  fn(j);
  fs.writeFileSync(file, JSON.stringify(j, null, 2) + "\n");
};
const seedPrefill = (root) => {
  const pre = path.join(root, "ddd", "07-define", ".prefill");
  fs.mkdirSync(pre, { recursive: true });
  fs.writeFileSync(path.join(pre, "billing.md"), "# billing brief (seed)\n");
};

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ddd-exit-codes-"));
try {
  // 1. Success paths are 0.
  {
    const root = materialise("mealkit", path.join(tmp, "ok"));
    const define = path.join(root, "ddd", "07-define", "define.json");
    expect("prefill default", run(root, "define", "prefill", "ddd"), 0, { out: "DEFINE pre-fill" });
    expect("prefill --json", run(root, "define", "prefill", "ddd", "--json"), 0, { out: '"facts"' });
    expect("prefill --write", run(root, "define", "prefill", "ddd", "--write"), 0, { out: "wrote draft" });
    seedPrefill(root);
    expect("render --check-only", run(root, "define", "render", "ddd", "--check-only"), 0, { out: "lint: OK" });
    assert(fs.existsSync(path.join(root, "ddd/07-define/.prefill/billing.md")), "invariant 7: --check-only must keep .prefill/");
    expect("render --context", run(root, "define", "render", "ddd", "--context", "billing"), 0, { out: "wrote" });
    assert(fs.existsSync(path.join(root, "ddd/07-define/.prefill/billing.md")), "invariant 7: --context must keep .prefill/");
    // A fresh --write already rewrote define.json above; from here on render must not touch it.
    const afterWrite = fs.readFileSync(define);
    expect("render full", run(root, "define", "render", "ddd"), 0, { out: "removed" });
    assert(!fs.existsSync(path.join(root, "ddd/07-define/.prefill")), "invariant 7: a full render must remove .prefill/");
    assert(Buffer.compare(afterWrite, fs.readFileSync(define)) === 0, "invariant 3: render must not modify define.json");
  }

  // 2. Lint failures are 1, render nothing, keep the briefs.
  {
    const root = materialise("mealkit", path.join(tmp, "lint"));
    editJson(path.join(root, "ddd", "07-define", "define.json"), (j) => { j.canvases[0].purpose = "TODO: write this later"; });
    seedPrefill(root);
    const canvas = path.join(root, "ddd", "07-define", "subscriptions", "bounded-context-canvas.md");
    const before = fs.readFileSync(canvas);
    expect("render lint failure", run(root, "define", "render", "ddd"), 1, { out: "lint error(s) — nothing rendered" });
    expect("render --check-only lint failure", run(root, "define", "render", "ddd", "--check-only"), 1, { out: "purpose still a TODO/draft" });
    expect("render --force lint failure", run(root, "define", "render", "ddd", "--force"), 1);
    assert(Buffer.compare(before, fs.readFileSync(canvas)) === 0, "a lint failure must not rewrite a canvas");
    assert(fs.existsSync(path.join(root, "ddd/07-define/.prefill/billing.md")), "invariant 7: a lint failure must keep .prefill/");
  }

  // 3. Usage errors are 2.
  {
    const root = materialise("mealkit", path.join(tmp, "usage"));
    expect("render bogus flag", run(root, "define", "render", "ddd", "--bogus"), 2, { err: "error:" });
    expect("prefill bad choice", run(root, "define", "prefill", "ddd", "--mode", "sometimes"), 2, { err: "invalid choice" });
    expect("prefill extra positional", run(root, "define", "prefill", "ddd", "extra"), 2, { err: "unrecognized arguments" });
    expect("render missing value", run(root, "define", "prefill", "ddd", "--depth"), 2);
    expect("render --help", run(root, "define", "render", "--help"), 0, { out: "usage:" });
  }

  // 4. Missing input: exit 1 with the Python-era message, as the goldens pin it.
  {
    const root = materialise("truncated-3", path.join(tmp, "missing"));
    expect("render without define.json", run(root, "define", "render", "ddd"), 1, { err: "not found — run ddd define prefill --write first" });
    expect("prefill missing workspace", run(root, "define", "prefill", "nowhere"), 1, { err: "does not exist" });
    expect("prefill unknown context", run(root, "define", "prefill", "ddd", "--context", "nope"), 1, { err: "unknown context id(s)" });
    fs.rmSync(path.join(root, "ddd", "03-decompose"), { recursive: true });
    expect("prefill without decompose.json", run(root, "define", "prefill", "ddd"), 1, { err: "decompose.json missing" });
  }

  // 5. Generated-line guard (invariant 4): a canvas without the marker is skipped, --force rewrites it.
  {
    const root = materialise("mealkit", path.join(tmp, "guard"));
    const canvas = path.join(root, "ddd", "07-define", "billing", "bounded-context-canvas.md");
    const edited = fs.readFileSync(canvas, "utf8").split("\n").filter((l) => !l.includes(MARK)).join("\n");
    fs.writeFileSync(canvas, edited);
    expect("render with hand-edited canvas", run(root, "define", "render", "ddd"), 0, { out: "skipped (hand-edited, no marker; use --force to overwrite)" });
    assert(fs.readFileSync(canvas, "utf8") === edited, "invariant 4: a hand-edited canvas must be left alone without --force");
    expect("render --force", run(root, "define", "render", "ddd", "--force"), 0, { out: "wrote" });
    assert(fs.readFileSync(canvas, "utf8").includes(MARK), "invariant 4: --force must rewrite the canvas with its marker");
  }
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

if (failures.length) {
  console.error("exit-codes verification FAILED:");
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log("define prefill: 0 on success, 1 on missing input, 2 on usage; define render: 0 rendered, 1 lint, 2 usage; invariants 3, 4, 7 hold");
console.log(MARKER);
