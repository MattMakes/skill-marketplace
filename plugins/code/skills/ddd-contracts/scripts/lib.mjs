export function findRelationship(A, producer, consumers) {
  const dc = asDict(get(A, "decompose"));
  const rels = asList(get(dc, "relationships")).filter(isDict);
  const ctxs = new Set(ids(get(dc, "bounded_contexts")));
  for (const c of consumers) {
    if (ctxs.has(producer) && ctxs.has(c)) {
      for (const r of rels) if (get(r, "upstream") === producer && get(r, "downstream") === c) return get(r, "id");
      for (const r of rels) if (setEq(new Set([get(r, "upstream"), get(r, "downstream")]), new Set([producer, c]))) return get(r, "id");
    }
  }
  return null;
}

// The relationship define recorded for this collaborator on the context's canvas.
export function canvasRelationship(A, ctx, collaborator) {
  for (const c of asList(get(asDict(get(A, "define")), "canvases"))) {
    if (!isDict(c) || get(c, "context") !== ctx) continue;
    for (const side of ["inbound", "outbound"]) {
      for (const coll of asList(get(c, side))) {
        if (isDict(coll) && get(coll, "collaborator") === collaborator) return get(coll, "relationship");
      }
    }
  }
  return null;
}

export function decomposePattern(A, aId, bId) {
  for (const r of asList(get(asDict(get(A, "decompose")), "relationships"))) {
    if (isDict(r) && setEq(new Set([get(r, "upstream"), get(r, "downstream")]), new Set([aId, bId]))) return get(r, "pattern");
  }
  return null;
}

export const alias = (p) => (typeof p === "string" && has(PATTERN_ALIASES, p) ? PATTERN_ALIASES[p] : p);

export function firstPattern(...candidates) {
  for (const c of candidates) if (PATTERNS.includes(alias(c))) return alias(c);
  return null;
}

// How our context wraps an external system: define's canvas relationship, else a decompose
// relationship, else `conformist`.
export function wrapperPattern(A, ctx, ext) {
  const p = firstPattern(canvasRelationship(A, ctx, ext), decomposePattern(A, ctx, ext));
  return p === "anticorruption-layer" || p === "conformist" ? p : or(p, "conformist");
}

export function teamsOwning(A, ctxIds) {
  const seen = [];
  for (const t of asList(get(asDict(get(A, "organise")), "teams"))) {
    if (!isDict(t)) continue;
    const owns = asList(get(t, "owns_contexts"));
    if (ctxIds.some((c) => owns.includes(c)) && !seen.includes(get(t, "id"))) seen.push(get(t, "id"));
  }
  return seen;
}

// Headings of glossary.md, as Python's `^#{1,6}\s+(.+?)\s*$` under re.M finds them.
export function glossaryHeadings(text) {
  const out = [];
  for (const m of String(text).matchAll(/^#{1,6}\s+(.+?)\s*$/gm)) out.push(m[1]);
  return out;
}

export function glossaryAnchor(A, rel, domain, names) {
  const text = get(A, "glossary_text");
  if (text === null) return null;
  const want = slug(`${pyStr(names.has(domain) ? names.get(domain) : domain)} context`);
  for (const h of glossaryHeadings(text)) if (slug(h) === want) return `${rel}/glossary.md#${want}`;
  return `${rel}/glossary.md`;
}

// "In plain words" block (envelope `plain_words`, artifact-contract.md section 3).
export function plainWordsBlock(doc) {
  const pw = get(asDict(doc), "plain_words");
  if (!isDict(pw)) return [];
  const [what, decided, assumed, riskiest] = ["what", "decided", "assumed", "riskiest"].map((k) => strip(pyStr(or(get(pw, k), ""))));
  if (!(what || decided || assumed || riskiest)) return [];
  const block = ["## In plain words", ""];
  if (what) block.push(what, "");
  for (const [label, value] of [["Decided", decided], ["Assumed", assumed], ["Riskiest", riskiest]]) {
    if (value) block.push(`**${label}:** ${value}`, "");
  }
  return [...block, "---", ""];
}

// ---------------------------------------------------------------------------
// Argument parsing: the argparse subset each subcommand used (an optional positional
// defaulting to `ddd`, `--flag value`, `--flag=value`, unique prefixes, choices,
// store_true, -h/--help). Usage errors are not golden-recorded, so the wording is plain.
// ---------------------------------------------------------------------------
export class UsageError extends Error {}

export function parseArgs(argv, options) {
  const res = { help: false, ddd_dir: "ddd" };
  for (const [name, o] of Object.entries(options)) res[o.dest] = o.flag ? false : (o.default ?? null);
  const names = Object.keys(options);
  const positional = [];
  let onlyPositional = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (onlyPositional || !a.startsWith("-") || a === "-") { positional.push(a); continue; }
    if (a === "--") { onlyPositional = true; continue; }
    if (a === "-h" || a === "--help") { res.help = true; return res; }
    const eq = a.indexOf("=");
    let name = eq >= 0 ? a.slice(0, eq) : a;
    const inline = eq >= 0 ? a.slice(eq + 1) : undefined;
    if (!options[name]) {
      const m = names.filter((n) => n.startsWith(name));
      if (m.length === 1) name = m[0];
      else if (m.length > 1) throw new UsageError(`ambiguous option: ${name} could match ${m.join(", ")}`);
      else throw new UsageError(`unrecognized arguments: ${a}`);
    }
    const o = options[name];
    if (o.flag) {
      if (inline !== undefined) throw new UsageError(`argument ${name}: ignored explicit argument '${inline}'`);
      res[o.dest] = true;
      continue;
    }
    let value = inline;
    if (value === undefined) {
      if (i + 1 >= argv.length || (argv[i + 1].startsWith("-") && argv[i + 1] !== "-")) throw new UsageError(`argument ${name}: expected one argument`);
      value = argv[++i];
    }
    if (o.choices && !o.choices.includes(value)) {
      throw new UsageError(`argument ${name}: invalid choice: '${value}' (choose from ${o.choices.map((c) => `'${c}'`).join(", ")})`);
    }
    res[o.dest] = value;
  }
  if (positional.length > 1) throw new UsageError(`unrecognized arguments: ${positional.slice(1).join(" ")}`);
  if (positional.length === 1) res.ddd_dir = positional[0];
  return res;
}

// The `main(argv, ctx)` wrapper every verb shares: parse, `<abs> does not exist` -> 2,
// IoError -> its message on stderr and its code, output through process.stdout.write so
// a piped stdout is never truncated by an early exit.
export async function runVerb({ argv, ctx, verb, options, usage, body }) {
  const prog = `ddd ${(ctx && ctx.words ? ctx.words : ["contracts", verb]).join(" ")}`;
  let a;
  try {
    a = parseArgs(argv, options);
  } catch (e) {
    if (e instanceof UsageError) {
      process.stderr.write(`usage: ${prog} ${usage}\n${prog}: error: ${e.message}\n`);
      return 2;
    }
    throw e;
  }
  if (a.help) {
    process.stdout.write(`usage: ${prog} ${usage}\n`);
    return 0;
  }
  const dddDir = path.resolve(a.ddd_dir);
  if (!(exists(dddDir) && fs.statSync(dddDir).isDirectory())) {
    process.stderr.write(`error: ${dddDir} does not exist\n`);
    return 2;
  }
  const outLines = [];
  const print = (s = "") => outLines.push(s);
  try {
    const code = body(a, dddDir, print);
    process.stdout.write(outLines.length ? outLines.join("\n") + "\n" : "");
    return code;
  } catch (e) {
    process.stdout.write(outLines.length ? outLines.join("\n") + "\n" : "");
    if (e instanceof IoError) {
      process.stderr.write(e.message + "\n");
      return e.exitCode;
    }
    throw e;
  }
}
