// json.load(): raises on bad JSON. Python's JSONDecodeError text cannot be reproduced
// from JSON.parse, so the message that follows `invalid JSON in <path>:` is V8's.
export function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, "utf8"));
}
export function loadJsonOrNull(p) {
  try { return loadJson(p); } catch { return null; }
}
// json.dump(indent=2, ensure_ascii=False) + "\n".
export function saveJson(p, data) {
  fs.writeFileSync(p, pyDumps(data, { indent: 2, ensureAscii: false }) + "\n");
}
// open(errors="ignore").read(), or None when the file cannot be read.
export function readText(p) {
  try { return fs.readFileSync(p, "utf8"); } catch { return null; }
}
export const exists = (p) => fs.existsSync(p);

export function ids(items, key = "id") {
  return asList(items).filter((x) => isDict(x) && get(x, key) !== null).map((x) => x[key]);
}

export function slug(s) {
  return strip(s).toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
}

// " ".join(w.capitalize() for w in s.split("-")): capitalize() lowercases the rest.
export function titlecase(mid) {
  return pyStr(mid).split("-").map((w) => (w ? w[0].toUpperCase() + w.slice(1).toLowerCase() : "")).join(" ");
}

// Covers everything contracts.md renders. plain_words is rendered too, so an edit to it
// must make the file stale; otherwise the summary a human reads can drift from the JSON.
export function entriesHash(entries, plainWords = null) {
  const payload = truthy(plainWords) ? [entries, plainWords] : entries;
  return createHash("sha256").update(pyDumps(payload, { sortKeys: true, ensureAscii: false }), "utf8").digest("hex").slice(0, 16);
}

// Property name of a connect payload entry: the leading identifier, so
// `completionEvidence{photoUris, meterReadings}` and `recipeIds[]` both name the property.
export function payloadName(p) {
  const s = pyStr(or(p, ""));
  const m = IDENT_RE.exec(s);
  if (m) return m[1];
  return strip(s) || null;
}

// Every property name in a schema, at any depth.
export function propertyNames(schema, out = new Set()) {
  if (isDict(schema)) {
    for (const [k, sub] of Object.entries(asDict(get(schema, "properties")))) {
      out.add(k);
      propertyNames(sub, out);
    }
    for (const key of ["items", "additionalProperties"]) {
      if (isDict(get(schema, key))) propertyNames(schema[key], out);
    }
  }
  return out;
}

// load_workspace: only the five upstream artifacts contracts.py reads; a corrupt one is
// an IO error (exit 2), a corrupt manifest is just an empty manifest.
export function loadWorkspace(dddDir) {
  const A = {};
  for (const s of ["discover", "decompose", "organise", "connect", "define"]) {
    const p = path.join(dddDir, FOLDER[s], `${s}.json`);
    if (exists(p)) {
      try {
        A[s] = loadJson(p);
      } catch (e) {
        throw new IoError(`error: invalid JSON in ${p}: ${e.message}`);
      }
    }
  }
  const mpath = path.join(dddDir, "manifest.json");
  if (exists(mpath)) A.manifest = or(loadJsonOrNull(mpath), {});
  A.glossary_text = readText(path.join(dddDir, "glossary.md"));
  return A;
}

export function relPrefix(A, dddDir) {
  const m = asDict(get(A, "manifest"));
  const base = path.basename(dddDir.replace(/\/+$/, ""));
  return String(or(get(m, "ddd_dir"), or(base, "ddd"))).replace(/^\/+|\/+$/g, "");
}

// (bounded-context ids in decompose order, id -> name, external-system ids, human-actor ids).
// `names` is a Map so a context without an id keys on null the way a Python dict does.
export function partySets(A) {
  const dc = asDict(get(A, "decompose"));
  const bcs = asList(get(dc, "bounded_contexts"));
  const contexts = ids(bcs);
  const names = new Map();
  for (const b of bcs) if (isDict(b)) names.set(get(b, "id"), or(get(b, "name"), get(b, "id")));
  const dv = asDict(get(A, "discover"));
  const externals = new Set(ids(get(dv, "external_systems")));
  const actors = new Set(ids(get(dv, "actors")));
  for (const p of asList(get(asDict(get(A, "connect")), "parties"))) {
    if (!isDict(p)) continue;
    (get(p, "kind") === "external-system" ? externals : actors).add(get(p, "id"));
  }
  return { contexts, names, externals, actors };
}

function blankMessage(mid, kind, producer, source) {
  return { id: mid, kind, producer, consumers: [], pattern: null, payload: [], response_payload: [],
    delivery: null, idempotency: "", description: "", name: "", channels: [], flows: [], vias: [], syncs: [], source };
}

// context id -> the set of deployable ids that host it (organise.deployables[].contexts).
export function placement(A) {
  const out = new Map();
  for (const d of asList(get(asDict(get(A, "organise")), "deployables"))) {
    if (!isDict(d)) continue;
    for (const c of asList(get(d, "contexts"))) {
      if (!truthy(c)) continue;
      if (!out.has(c)) out.set(c, new Set());
      out.get(c).add(get(d, "id"));
    }
  }
  return out;
}

// (cross-party messages, in-process messages), both as Maps in insertion order.
//
// Cross-party = each connect.messages[] entry whose consumer set differs from {producer}, plus
// each flow step between two different parties whose message has no messages[] entry, minus
// anything organise puts inside a single deployable. A human on one end is in scope (that is
// the UI/API contract); a human on both ends and `kind: response` are not. Everything
// uncertain stays cross-party: a contract too many is a review comment, too few is an outage.
export function crossParty(A) {
  const cn = asDict(get(A, "connect"));
  const { externals, actors } = partySets(A);
  const software = (p) => truthy(p) && !actors.has(p);
  const out = new Map();
  for (const m of asList(get(cn, "messages"))) {
    if (!isDict(m)) continue;
    const mid = get(m, "id");
    const cons = asList(get(m, "consumers")).filter(truthy);
    const producer = get(m, "producer");
    if (!truthy(mid) || !cons.length || setEq(new Set(cons), new Set([producer])) || get(m, "kind") === "response") continue;
    if (!software(producer) && !cons.some(software)) continue;
    const e = blankMessage(mid, get(m, "kind"), producer, "messages");
    Object.assign(e, {
      consumers: uniq(cons),
      pattern: get(m, "contract"),
      payload: [...asList(get(m, "payload"))],
      response_payload: [...asList(get(m, "response_payload"))],
      delivery: get(m, "delivery"),
      idempotency: strip(pyStr(or(get(m, "idempotency"), ""))),
      description: strip(pyStr(or(get(m, "description"), ""))),
      name: strip(pyStr(or(get(m, "name"), ""))),
      channels: asList(get(m, "channels")).filter(isDict),
    });
    out.set(mid, e);
  }
  for (const f of asList(get(cn, "flows"))) {
    if (!isDict(f)) continue;
    for (const s of asList(get(f, "steps"))) {
      if (!isDict(s)) continue;
      const mid = get(s, "message");
      const frm = get(s, "from");
      const to = get(s, "to");
      if (!truthy(mid) || get(s, "kind") === "response") continue;
      let e = out.get(mid);
      if (e === undefined) {
        if (!truthy(frm) || !truthy(to) || frm === to || !(software(frm) || software(to))) continue;
        e = blankMessage(mid, get(s, "kind"), frm, "flow");
        out.set(mid, e);
      }
      if (e.source === "flow" && truthy(to) && to !== e.producer && !e.consumers.includes(to)) e.consumers.push(to);
      const fid = get(f, "id");
      if (truthy(fid) && !e.flows.includes(fid)) e.flows.push(fid);
      if (truthy(get(s, "via"))) e.vias.push(s.via);
      e.syncs.push(truthy(get(s, "sync")));
    }
  }
  for (const e of out.values()) {
    if (e.source === "flow" && !truthy(e.delivery) && e.syncs.length && e.syncs.every(Boolean)) e.delivery = "sync";
  }
  const placed = placement(A);
  // The deployable hosting producer and every consumer, or null if that is not certain.
  const oneDeployable = (e) => {
    if (!placed.size) return null;
    const parties = [e.producer, ...e.consumers];
    if (parties.some((p) => !truthy(p) || actors.has(p) || externals.has(p))) return null;
    const units = parties.map((p) => placed.get(p) || new Set());
    if (units.some((u) => u.size !== 1)) return null;
    return units.every((u) => setEq(u, units[0])) ? [...units[0]][0] : null;
  };
  const inproc = new Map();
  for (const mid of [...out.keys()]) {
    const unit = oneDeployable(out.get(mid));
    if (truthy(unit)) {
      out.get(mid).deployable = unit;
      inproc.set(mid, out.get(mid));
      out.delete(mid);
    }
  }
  return { xp: out, inproc };
}

function setEq(a, b) {
  if (a.size !== b.size) return false;
  for (const x of a) if (!b.has(x)) return false;
  return true;
}

// sorted(inproc.items()): by message id.
export const sortedEntries = (m) => [...m.entries()].sort((a, b) => cmpStr(a[0], b[0]));

// (primary transport, the other channels as objects). The flow steps' `via` wins; a
// catalogue-only message falls back to its `channels[]`. A sync message never keeps `file`
// as primary when a synchronous transport is listed. The extra channels keep connect's whole
// {via, sync, delivery, note} object: a second transport is a second promise.
//
// Python picks `max(set(cands), key=cands.count)`, whose tie-break follows set iteration
// order; here a tie goes to the transport seen first, which is the only deterministic reading.
export function chooseVia(info) {
  const vias = asList(get(info, "vias")).filter(truthy);
  const objs = asList(get(info, "channels")).filter((c) => isDict(c) && truthy(get(c, "via")));
  const chan = objs.map((c) => c.via);
  const cands = vias.length ? vias : chan;
  if (!cands.length) return ["TODO", []];
  let primary = null;
  let best = -1;
  for (const v of uniq(cands)) {
    const n = cands.filter((x) => x === v).length;
    if (n > best) { best = n; primary = v; }
  }
  if (get(info, "delivery") === "sync" && !SYNC_VIAS.includes(primary)) {
    primary = [...cands, ...chan].find((v) => SYNC_VIAS.includes(v)) ?? primary;
  }
  const detail = new Map();
  for (const c of objs) detail.set(c.via, { ...c });
  // a transport seen only on a flow step has no object upstream, so it gets a bare one
  const others = uniq([...vias, ...chan]).filter((v) => v !== primary).map((v) => detail.get(v) || { via: v });
  return [primary, others];
}

