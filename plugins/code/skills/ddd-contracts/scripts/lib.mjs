// `file (at-most-once, async): the warehouse picks the week up from the nightly pick-list`.
export function channelLines(chans) {
  const out = [];
  for (const c of asList(chans)) {
    if (!isDict(c) || !truthy(get(c, "via"))) continue;
    const bits = truthy(get(c, "delivery")) ? [pyStr(c.delivery)] : [];
    if (get(c, "sync") !== null) bits.push(truthy(c.sync) ? "sync" : "async");
    let line = pyStr(c.via) + (bits.length ? ` (${bits.join(", ")})` : "");
    if (truthy(get(c, "note"))) line += `: ${pyStr(c.note)}`;
    out.push(line);
  }
  return out.join("; ");
}

