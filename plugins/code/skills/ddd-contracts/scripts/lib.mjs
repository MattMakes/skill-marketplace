// ---------------------------------------------------------------------------
// Python value semantics.
// ---------------------------------------------------------------------------
export const isDict = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
export const has = (o, k) => isDict(o) && Object.prototype.hasOwnProperty.call(o, k);
// `d.get(k)`: None when absent; the value (which may itself be None) otherwise.
export const get = (o, k, dflt = null) => (has(o, k) ? o[k] : dflt);
// Python truthiness: None, False, 0, "", [], {} are false.
export function truthy(v) {
  if (v === null || v === undefined || v === false || v === 0) return false;
  if (typeof v === "string" || Array.isArray(v)) return v.length > 0;
  if (isDict(v)) return Object.keys(v).length > 0;
  return true;
}
// `x or y`.
export const or = (a, b) => (truthy(a) ? a : b);
// `str.strip()` / `rstrip()`: Python strips Unicode whitespace, as JS trim does.
export const strip = (s) => String(s).trim();
export const isKebab = (s) => KEBAB_RE.test(s);
// `[x for x in list if isinstance(x, dict)]` guard for values that may not be a list.
export const asList = (v) => (Array.isArray(v) ? v : []);
export const asDict = (v) => (isDict(v) ? v : {});
// `x in some_list` with Python `==` (strings and None only ever get here).
export const pyIn = (v, list) => asList(list).some((x) => x === v || (x === null && v === undefined));
// sorted() of strings: Python orders by code point; JS `<` orders by UTF-16 unit, the
// same thing for everything in the BMP.
export const cmpStr = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
export const sorted = (xs) => [...xs].sort(cmpStr);
// list(dict.fromkeys(xs)): dedupe, first occurrence wins.
export const uniq = (xs) => [...new Set(xs)];
// str.format `{x:<N}`: left-justify by code points.
export const ljust = (s, n) => {
  const len = [...s].length;
  return len >= n ? s : s + " ".repeat(n - len);
};

